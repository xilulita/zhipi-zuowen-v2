    var out = [];
    paragraphs.forEach(function (para, pi) {
      para.forEach(function (sent) {
        if (!sent.a) return;
        out.push({
          para: pi,
          type: sent.a.type,
          tag: sent.a.tag,
          sentence: sent.t,
          note: sent.a.note,
          fix: sent.a.fix
        });
      });
    });
    return out;
